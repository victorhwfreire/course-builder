"""Gera o port do course-builder para o Codex a partir desta fonte.

Uso: python -B scripts/portar_codex.py <pasta do plugin Codex>
Escreve <destino>/.codex-plugin/plugin.json, <destino>/README.md e <destino>/skills/build-module/
(SKILL.md com o adaptador do Codex + agents, skills, schemas, examples, assets e o scaffold).
Sobrescreve os arquivos gerados; não apaga arquivos que só existam no destino.
"""
import json
import re
import shutil
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent

ADAPTADOR = """## Codex runtime adapter

This is the Codex port of the Claude course-builder plugin, generated by
`scripts/portar_codex.py` from the Claude source. All relative resource paths in
this skill and its agent briefs resolve from the directory containing this
SKILL.md, which is also the **plugin root** the briefs mention. Output paths
resolve from the user's working directory. Resolve both to absolute paths before
dispatching.

- The input spec path comes from the user's message after `$build-module` (also
  accept a natural-language request or the legacy `/course-builder:build-module`).
- Use `collaboration.spawn_agent` or the available Codex `spawn_agent` to dispatch
  one role at a time. Read `agents/<slug>.md` first and pass its full instructions,
  this adapter, the absolute skill directory, canonical spec, output directory,
  and optional baseline to the subagent. These markdown briefs are bundled role
  instructions, not registered Claude agent types. Inherit the current model.
  Wait for completion before the next role. Reuse or close completed agents if
  needed to stay within the runtime limit. If delegation tools are unavailable,
  execute the same role briefs sequentially yourself and disclose that fallback.
- `Read`, `Write`, `Edit`, `Glob`, `Grep`, and `Bash` in role briefs mean the
  available Codex filesystem and shell tools. Use PowerShell on Windows; use Bash
  only for scripts that require it. `WebSearch`/`WebFetch` mean the available web tools.
- `Skill` means read and apply `skills/<name>/SKILL.md` from this directory; the
  supporting skills and their assets are bundled here.
- Claude PreToolUse hooks are not registered by this Codex port. Apply their
  intent as instructions before tool calls: use defanged example credentials
  such as `ak_exemplo-CURSO-chave-falsa-NAO-USAR`; never write real or realistic
  provider tokens in educational artifacts. Do not run destructive operations
  (`git push --force`, `git reset --hard`, recursive deletion, `DROP TABLE`).
  Agents never run git. These are behavioral checks, not automatic hook blocks.
- Follow current user authorization and higher-priority Codex instructions.
  Generate, check and repair the complete reviewable artifact bundle. Phase 0
  only stops on an invalid spec; do not request approval for a valid spec.
  The final QA gate concerns publishing/shipping, not local artifact creation.
  If publishing was already explicitly authorized, do not ask again. Otherwise
  return the finished bundle and QA report, and request approval only if actual
  publication is the next requested action. Explain any remaining skill-imposed
  pause with a link to this SKILL.md and the relevant quoted instruction.
"""

DESPACHO = """## Dispatch mechanics (applies to every phase)

- Dispatch each role using the Codex runtime adapter above, passing the spec path, the output dir, the plugin root (this skill's directory) and, for `qa-reviewer` only, the baseline path.
- One agent per dispatch. Wait for each agent to return before dispatching the next (the phases are sequential; handoffs are ordered).
- **Agents do NOT commit.** No agent runs `git`. Git is handled by the human (or by you, only after Gate HITL #2 greenlight and only if the human asks). This is a hard rule.
- **Report progress per phase** to the human: which agent ran, what artifact(s) it produced, and any flags it raised. Keep the human oriented — a one-line status per dispatch is enough.
- Apply the behavioral guardrails from the Codex runtime adapter; no automatic Claude hooks are installed.
"""


def bloco(texto, nome, novo):
    padrao = re.compile(rf"<!-- claude:{nome}:inicio -->\n.*?<!-- claude:{nome}:fim -->\n?", re.S)
    if not padrao.search(texto):
        sys.exit(f"Marcador claude:{nome} não encontrado em commands/build-module.md")
    return padrao.sub(lambda _: novo, texto)


def skill_md(versao):
    comando = (RAIZ / "commands" / "build-module.md").read_text(encoding="utf-8")
    corpo = re.sub(r"\A---\n.*?\n---\n", "", comando, flags=re.S)
    corpo = bloco(corpo, "despacho", DESPACHO)
    corpo = bloco(corpo, "ganchos", "Guardrails are applied through the Codex runtime adapter; they are not automatic hooks.\n")
    corpo = corpo.replace("# /course-builder:build-module — course-builder orchestrator", "# Build module")
    corpo = corpo.replace(
        "The human invoked `/course-builder:build-module <spec-path>` with `$ARGUMENTS`.",
        "The human requested `$build-module <spec-path>`.")
    corpo = corpo.replace("you do not author artifacts yourself.",
                          "use the Codex dispatch adapter above, including its sequential fallback if delegation is unavailable.")
    corpo = corpo.replace("(`${CLAUDE_PLUGIN_ROOT}` when the runtime sets it)", "(in this port, the directory containing this SKILL.md)")
    corpo = corpo.replace("$ARGUMENTS", "the supplied spec path").replace("/course-builder:build-module", "$build-module")
    corpo = corpo.replace("re-run `/build-module`", "re-run `$build-module`")
    descricao = ("Build a complete course module from module.spec.yaml using the course-builder workflow. Use for build-module, "
                 "course-builder, ementa, lesson plans, slides Gamma, instructor scripts and a course portal; supports repo-bugs, "
                 "projeto-pitch, debate-caso and estudo-dirigido (expository lessons, single-source generators, study guide PDF, "
                 "monitor, interactive and instructor guides).")
    return f"---\nname: build-module\ndescription: {descricao}\n---\n\n{ADAPTADOR}\n{corpo.lstrip()}"


def main(destino):
    destino = Path(destino)
    versao = json.loads((RAIZ / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]
    skill = destino / "skills" / "build-module"
    skill.mkdir(parents=True, exist_ok=True)
    (skill / "SKILL.md").write_text(skill_md(versao), encoding="utf-8")
    ignorar = shutil.ignore_patterns("__pycache__", "*.pyc", "*.bak-*")
    for pasta in ("agents", "skills", "schemas", "examples", "assets"):
        if (RAIZ / pasta).is_dir():
            shutil.copytree(RAIZ / pasta, skill / pasta, dirs_exist_ok=True, ignore=ignorar)
    (skill / "scripts").mkdir(exist_ok=True)
    shutil.copy2(RAIZ / "scripts" / "scaffold_preparacao.py", skill / "scripts" / "scaffold_preparacao.py")
    descricao = ("Gera módulos de curso a partir de module.spec.yaml: ementa, aulas, exercícios, roteiros, slides Gamma e portal; "
                 "no modo estudo-dirigido, fonte única por aula, geradores, estudo dirigido em PDF e guias do monitor, interativo e do professor.")
    manifesto = {
        "name": "course-builder",
        "version": f"{versao}+codex.1",
        "description": descricao,
        "author": {"name": "IA Para Devs (CESAR 2026)"},
        "skills": "./skills/",
        "interface": {
            "displayName": "Course Builder",
            "shortDescription": "Crie módulos de curso com build-module.",
            "longDescription": descricao,
            "developerName": "Local developer",
            "category": "Productivity",
            "capabilities": [],
            "defaultPrompt": "Use $build-module com meu module.spec.yaml para criar o módulo completo.",
        },
    }
    (destino / ".codex-plugin").mkdir(exist_ok=True)
    (destino / ".codex-plugin" / "plugin.json").write_text(json.dumps(manifesto, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (destino / "README.md").write_text(
        f"# Course Builder para Codex\n\n"
        f"Gerado por `scripts/portar_codex.py` a partir do plugin course-builder {versao} do Claude. Para atualizar, rode o script de "
        f"novo na fonte do Claude; não edite esta cópia.\n\n"
        f"Em uma nova conversa, use `$build-module C:/caminho/module.spec.yaml`. Os resultados ficam em `out/<codigo-do-curso>/` "
        f"no diretório de trabalho.\n\n"
        f"Inclui os briefs dos agentes, as skills auxiliares, o schema, os specs de exemplo, os geradores do modo estudo-dirigido "
        f"(`assets/`) e `scripts/scaffold_preparacao.py`, dentro de `skills/build-module/`. Os agentes são despachados pelas "
        f"ferramentas do Codex, herdando o modelo da conversa. Os hooks PreToolUse do Claude viram instruções comportamentais, "
        f"sem bloqueio automático.\n", encoding="utf-8")
    print(f"Port {versao}+codex.1 escrito em {destino}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
